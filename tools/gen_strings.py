LANGS = {"values": 1, "values-ru": 2, "values-tg": 3}
def esc(s):
    return html.escape(s, quote=False).replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "src", "main", "res")
keys = [r[0] for r in S]
assert len(keys) == len(set(keys)), "duplicate keys"
for d, i in LANGS.items():
    with open(os.path.join(root, d, "strings.xml"), "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Сгенерировано tools/gen_strings.py — правьте таблицу там -->\n<resources>\n')
        for r in S:
            tr = ' translatable="false"' if r[0] in ("app_name", "slogan") and d == "values" else ""
            if r[0] in ("app_name", "slogan") and d != "values": continue
            f.write(f'    <string name="{r[0]}"{tr}>{esc(r[i])}</string>\n')
        f.write("</resources>\n")
print(len(S), "strings x", len(LANGS))
